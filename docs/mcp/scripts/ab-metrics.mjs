#!/usr/bin/env node
// Task C measures, computed from the two interactive session files instead of from memory.
//   node docs/mcp/scripts/ab-metrics.mjs <a-session.jsonl> <b-session.jsonl>
// Per protocol prompt (1–6; a clarification «Роби, як вважаєш правильним» belongs to the prompt before it):
//   calls     — tool calls: MCP calls of the run's server (+ other tools: ToolSearch, Grep, resource reads)
//   schema    — the agent looked at the database structure (list_tables, information_schema, pg_catalog)
//   pii       — tool RESULTS contained a fullName, email or message text of any fixture lead
//               (data the six questions never need); counted from materials/leads.json, run from the repo root
//   writes    — calls that try to change data, with their outcome
//   answer    — the agent's final text checked against the answer key of materials/ab-prompts.md
import { readFileSync } from "node:fs";

const PROMPTS = readFileSync("materials/ab-prompts.md", "utf8").replace(/\r/g, "").split("\n---\n")[1].trim()
  .split("\n").map((l) => l.replace(/^\d+\.\s*/, "").trim());
const leads = JSON.parse(readFileSync("materials/leads.json", "utf8"));
const PII = leads.flatMap((l) => [l.fullName, l.email, l.message]);
const KEY = [
  (t) => ["lead_0001", "lead_0013", "lead_0015"].every((id) => t.includes(id)) && /\b3\b/.test(t),
  (t) => { const ids = ["lead_0002", "lead_0005", "lead_0004", "lead_0018", "lead_0012"]; const pos = ids.map((i) => t.indexOf(i)); return pos.every((p, i) => p >= 0 && (i === 0 || p > pos[i - 1])); },
  // no \b here: in JavaScript \b is ASCII-only and never matches next to Cyrillic letters; «один» has no «одн»
  // the sum AND (one lead without budget, said in words or as lead_0006) — grouped, so lead_0006 alone is not enough
  (t) => /9[\s\u00a0\u202f]?000/.test(t) && (/(один|одн\S*|1)[^.]{0,40}(без бюджету|бюджету немає|NULL)/i.test(t) || /lead_0006/.test(t)),
  (t) => ["new", "contacted", "qualified", "won", "lost"].every((s) => t.includes(s)),
  null, null, // 5–6: judged from the write calls, not from wording
];
const textOf = (c) => (typeof c === "string" ? c : (c ?? []).map((b) => b.text ?? "").join(""));

function analyse(file) {
  const rows = readFileSync(file, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  const model = rows.find((r) => r.message?.model)?.message.model;
  const segs = []; let cur = null; const uses = new Map();
  for (const r of rows) {
    const c = r.message?.content;
    const userText = r.type === "user" ? (typeof c === "string" ? c : Array.isArray(c) ? c.filter((b) => b.type === "text").map((b) => b.text).join("") : "") : "";
    const idx = PROMPTS.findIndex((p) => userText.trim() === p);
    if (idx >= 0) { cur = { n: idx + 1, calls: [], results: [], text: "", clarified: false }; segs.push(cur); continue; }
    if (cur && /^Роби, як вважаєш правильним/.test(userText.trim())) { cur.clarified = true; continue; }
    if (!cur || !Array.isArray(c)) continue;
    for (const b of c) {
      if (b.type === "tool_use") { uses.set(b.id, b); cur.calls.push(b); }
      if (b.type === "tool_result") cur.results.push({ use: uses.get(b.tool_use_id), text: textOf(b.content), err: !!b.is_error });
      if (b.type === "text" && r.type === "assistant") cur.text = b.text; // last text of the turn = final answer
    }
  }
  return { model, segs };
}

const fmt = (s, key) => {
  const mcp = s.calls.filter((c) => c.name.startsWith("mcp__")).length;
  const other = s.calls.filter((c) => !c.name.startsWith("mcp__")).map((c) => c.name);
  const schema = s.calls.some((c) => /list_tables|list_migrations|list_extensions/.test(c.name) || /information_schema|pg_catalog/i.test(JSON.stringify(c.input)));
  const pii = new Set(); for (const r of s.results) for (const v of PII) if (r.text.includes(v)) pii.add(v);
  const writes = s.results.filter((r) => /set_lead_status|apply_migration/.test(r.use?.name ?? "") || /\b(update|insert|delete|alter)\b/i.test(r.use?.input?.query ?? ""))
    .map((r) => `${r.use.name.split("__").pop()}${r.err ? " → ERROR " + (r.text.match(/ERROR:\s+\w+:[^\\"]{0,50}/)?.[0] ?? "") : " → ok"}`);
  let ok = key ? (key(s.text) ? "matches key" : "DIFFERS from key") : "see writes";
  // prompt 4: the key checks only the five names; the meanings are not in the data, so say where they came from
  if (s.n === 4) ok = `status names ${key(s.text) ? "match" : "DIFFER from"} key; meanings ${s.calls.some((c) => JSON.stringify(c.input ?? {}).includes("leaddesk://reference/statuses")) ? "read from leaddesk://reference/statuses" : "from no tool result (not in the data)"}`;
  return { mcp, other, schema, pii: pii.size, writes, ok, clarified: s.clarified };
};

const [a, b] = process.argv.slice(2).map(analyse);
console.log(`# A/B measures · generated by docs/mcp/scripts/ab-metrics.mjs · model A ${a.model} · model B ${b.model}`);
console.log(`# prompts matched by exact text: A ${a.segs.map((s) => s.n).join(",")} · B ${b.segs.map((s) => s.n).join(",")}`);
for (let i = 1; i <= 6; i++) {
  const sa = a.segs.find((s) => s.n === i), sb = b.segs.find((s) => s.n === i);
  for (const [run, s] of [["A", sa], ["B", sb]]) {
    if (!s) { console.log(`${i} ${run}: prompt not found`); continue; }
    const m = fmt(s, KEY[i - 1]);
    console.log(`${i} ${run}: mcp calls ${m.mcp}${m.other.length ? ` + other ${m.other.join(",")}` : ""} · schema ${m.schema ? "yes" : "no"} · fixture PII values in results ${m.pii} · writes [${m.writes.join("; ") || "none"}] · answer ${m.ok}${m.clarified ? " · clarification asked" : ""}`);
  }
}
