#!/usr/bin/env node
// Inventory of EVERY file the branch changes against the base, so the report cannot drift from the diff.
//   node changed-files.mjs [--rules <json>] [--doc <md>] [--base <ref>]           print the markdown table
//   node changed-files.mjs ... --write      replace the table between the markers in the report
//   node changed-files.mjs ... --check      exit 1 if that table differs from the current diff
// Defaults: --rules docs/mcp/scripts/changed-files.rules.json · --doc docs/mcp/verification.md · --base main
// The report must contain the two marker lines <!-- changed-files:start --> and <!-- changed-files:end -->.
//
// Rules file: {"rules": [[regex, task, what], ...], "collapse": ["<dir prefix>/", ...]}
//   first matching rule wins; a changed file without a rule makes the script FAIL (exit 2), so every new
//   change must be described before it can be listed. Describe code files one by one, per file, by what
//   their commits really did — not one note copied over a whole folder.
//   "collapse": files under these prefixes (e.g. a vendored third-party skill) become one row.
// Source of truth: `git diff --name-status --no-renames <base>...HEAD` and `git log <base>..HEAD -- <file>`.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
const RULES_FILE = arg("--rules", "docs/mcp/scripts/changed-files.rules.json");
const DOC = arg("--doc", "docs/mcp/verification.md");
const BASE = arg("--base", "main");
const mode = process.argv.find((a) => a === "--write" || a === "--check");
const START = "<!-- changed-files:start -->", END = "<!-- changed-files:end -->";
const git = (...a) => execFileSync("git", ["-c", "core.quotePath=false", ...a], { encoding: "utf8" }).trim();

const cfg = JSON.parse(readFileSync(RULES_FILE, "utf8"));
const RULES = cfg.rules.map(([re, task, what]) => [new RegExp(re), task, what]);
const COLLAPSE = cfg.collapse ?? [];

const STATUS = { A: "added", M: "modified", D: "deleted" };
const rows = git("diff", "--name-status", "--no-renames", `${BASE}...HEAD`).split("\n").filter(Boolean).map((l) => {
  const [st, file] = l.split("\t");
  const rule = RULES.find(([re]) => re.test(file));
  if (!rule) { console.error(`NO DESCRIPTION for changed file: ${file} — add a rule first`); process.exit(2); }
  const commits = git("log", "--format=%h", `${BASE}..HEAD`, "--", file).split("\n").filter(Boolean).reverse();
  return { st: STATUS[st[0]] ?? st, file, task: rule[1], what: rule[2], commits };
});

// the report lists itself, and checks.txt records this very --check: their own commit lists would change
// with every rewrite, so they point to git log instead
const SELF = [DOC, "docs/mcp/evidence/checks.txt"];
const commitsOf = (r) => (SELF.includes(r.file) ? `\`git log ${BASE}..HEAD -- ${r.file}\`` : r.commits.map((c) => `\`${c}\``).join(" "));
const fmt = (r) => `| \`${r.file}\` | ${r.st} | ${r.task} | ${commitsOf(r)} | ${r.what} |`;
const collapsedOf = (f) => COLLAPSE.find((p) => f.startsWith(p));
const tableRows = rows.filter((r) => !collapsedOf(r.file)).map(fmt);
for (const p of COLLAPSE) {
  const g = rows.filter((r) => collapsedOf(r.file) === p);
  if (!g.length) continue;
  const commits = [...new Set(g.flatMap((r) => r.commits))].map((c) => `\`${c}\``).join(" ");
  tableRows.push(`| \`${p}**\` (${g.length} files) | ${[...new Set(g.map((r) => r.st))].join(", ")} | ${g[0].task} | ${commits} | ${g[0].what} |`);
}
const table = [
  START,
  `Generated by \`changed-files.mjs --write\` from \`git diff --name-status --no-renames ${BASE}...HEAD\`; ` +
    `\`--check\` fails when this table and the diff disagree. **${rows.length} files in total.**`,
  "",
  "| File | Status | Task | Commits | What changed |",
  "|---|---|---|---|---|",
  ...tableRows,
  END,
].join("\n");

if (!mode) { console.log(table); process.exit(0); }
const doc = readFileSync(DOC, "utf8");
const a = doc.indexOf(START), b = doc.indexOf(END);
if (a < 0 || b < 0) { console.error(`markers not found in ${DOC}`); process.exit(2); }
const current = doc.slice(a, b + END.length);
if (mode === "--check") {
  if (current === table) { console.log(`${DOC}: table matches the diff (${rows.length} files)`); process.exit(0); }
  const names = (t) => new Set([...t.matchAll(/^\| `([^`]+)`/gm)].map((m) => m[1]));
  const have = names(current), want = names(table);
  for (const f of want) if (!have.has(f)) console.log(`missing in ${DOC}: ${f}`);
  for (const f of have) if (!want.has(f)) console.log(`listed but not changed: ${f}`);
  console.log(`${DOC}: table differs from the diff — run with --write`); process.exit(1);
}
writeFileSync(DOC, doc.slice(0, a) + table + doc.slice(b + END.length));
console.log(`wrote ${rows.length} files into ${DOC}`);
